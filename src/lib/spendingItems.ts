// Items for one period, already grouped into the year buckets the UI shows.
// Undated rows collect under "No date" and always sort last.
export interface YearGroup {
  year: string;
  total: number;
  items: SpendItem[];
}

export function groupByYear(periodKey: string): YearGroup[] {
  const buckets = new Map<string, SpendItem[]>();
  for (const item of SPEND_ITEMS) {
    if (item.k !== periodKey) continue;
    const year = item.d ? item.d.slice(0, 4) : "No date";
    const bucket = buckets.get(year);
    if (bucket) bucket.push(item);
    else buckets.set(year, [item]);
  }
  return [...buckets.entries()]
    .map(([year, items]) => ({
      year,
      total: items.reduce((sum, i) => sum + i.a, 0),
      items: items.sort((a, b) => (b.d ?? "").localeCompare(a.d ?? "")),
    }))
    .sort((a, b) =>
      a.year === "No date" ? 1 : b.year === "No date" ? -1 : b.year.localeCompare(a.year)
    );
}
